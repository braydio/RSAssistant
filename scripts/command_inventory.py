#!/usr/bin/env python3
"""Generate a Markdown inventory of Discord commands from the cog sources (AST, no imports)."""
import ast
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
KINDS = {"command", "group", "hybrid_command", "hybrid_group"}


def deco_info(d):
    """Return (kind, name_kw, aliases) for a commands.* decorator, else None."""
    call = d if isinstance(d, ast.Call) else None
    func = call.func if call else d
    if isinstance(func, ast.Attribute) and func.attr in KINDS:
        name, aliases = None, []
        for kw in (call.keywords if call else []):
            if kw.arg == "name" and isinstance(kw.value, ast.Constant):
                name = kw.value.value
            if kw.arg == "aliases" and isinstance(kw.value, (ast.List, ast.Tuple)):
                aliases = [e.value for e in kw.value.elts if isinstance(e, ast.Constant)]
        return func.attr, name, aliases
    return None


def checks(fn):
    """Names of every non-command decorator (auth checks such as admin_only)."""
    out = []
    for d in fn.decorator_list:
        node = d.func if isinstance(d, ast.Call) else d
        name = node.attr if isinstance(node, ast.Attribute) else getattr(node, "id", "?")
        if name not in KINDS:
            out.append(name)
    return out


def inventory():
    rows = []
    for path in sorted((ROOT / "rsassistant" / "bot").rglob("*.py")):
        tree = ast.parse(path.read_text())
        for fn in [n for n in ast.walk(tree) if isinstance(n, (ast.AsyncFunctionDef, ast.FunctionDef))]:
            for d in fn.decorator_list:
                info = deco_info(d)
                if info:
                    kind, name, aliases = info
                    rows.append((name or fn.name, kind, aliases, checks(fn),
                                 str(path.relative_to(ROOT)), fn.lineno))
    return sorted(rows)


def main() -> int:
    rows = inventory()
    print("# Discord command inventory (generated by scripts/command_inventory.py)\n")
    print(f"{len(rows)} commands.\n")
    print("| Command | Kind | Aliases | Checks | Source |\n| --- | --- | --- | --- | --- |")
    for name, kind, aliases, chk, src, line in rows:
        print(f"| `{name}` | {kind} | {', '.join(f'`{a}`' for a in aliases) or '-'} | "
              f"{', '.join(chk) or '**none**'} | `{src}:{line}` |")
    return 0


if __name__ == "__main__":
    sys.exit(main())
